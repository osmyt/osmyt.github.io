// =========================================================
// Language toggle
// =========================================================
const langToggle = document.getElementById('langToggle');
const langToggleLabel = document.getElementById('langToggleLabel');
const htmlEl = document.documentElement;
const metaDescriptionEl = document.querySelector('meta[name="description"]');

function applyLanguage(lang) {
    const dict = translations[lang];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    htmlEl.setAttribute('lang', lang);
    htmlEl.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    document.body.classList.toggle('lang-ar', lang === 'ar');

    document.title = dict['meta.title'];
    if (metaDescriptionEl) metaDescriptionEl.setAttribute('content', dict['meta.description']);

    langToggleLabel.textContent = lang === 'ar' ? 'English' : 'العربية';
    langToggle.setAttribute('aria-label', lang === 'ar' ? 'Switch language to English' : 'Switch language to Arabic');

    try { localStorage.setItem('preferredLang', lang); } catch (e) { /* storage unavailable */ }
}

let currentLang = 'en';
try {
    currentLang = localStorage.getItem('preferredLang') || 'en';
} catch (e) { /* storage unavailable, default to English */ }

applyLanguage(currentLang);

langToggle.addEventListener('click', () => {
    currentLang = currentLang === 'ar' ? 'en' : 'ar';
    applyLanguage(currentLang);
});

